const dicts: Record<Language, Partial<Record<TKey, string>>> = { en, ka };

export function translate(lang: Language, key: TKey, vars?: Record<string, string | number>): string {
  let s = dicts[lang]?.[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Non-hook variant for stores / hooks. */
export function t(key: TKey, vars?: Record<string, string | number>): string {
  return translate(useSettings.getState().language, key, vars);
}

/** Hook: re-renders when the language changes. */
export function useT() {
  const lang = useSettings((s) => s.language);
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

